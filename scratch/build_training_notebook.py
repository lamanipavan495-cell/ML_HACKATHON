add_md("""## 7. Hidden Markov Model & Viterbi Route Reconstruction
A standalone classifier evaluates each GPS point independently. When two roads run parallel, noisy GPS measurements cause the classifier's top prediction to alternate between them, causing disconnected jumps (**raw route continuity is only ~89.4%**).

We implement a **Hidden Markov Model (HMM)** with log-space **Viterbi Decoding**:
* **Emission Probability:** $P(z_t \mid s_t) \propto P_{\\text{RF}}(y=1) \\cdot \\exp(-d_\\perp^2 / 2\\sigma^2)$
* **Transition Probability:** $P(s_t \\mid s_{t-1})$ checks network topological adjacency and penalizes graph distance gaps.
* **Viterbi Algorithm:** Uses dynamic programming to find the globally optimal, continuous sequence of road segments across the entire trip.""")

